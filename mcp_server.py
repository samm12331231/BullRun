def handle_tool_call(name: str, arguments: dict) -> dict:
    """Dispatch MCP tool calls to BullRun's multi-agent engines."""
    try:
        if name == "scout_regime_scan":
            result = scout_agent.run()
            return {"content": [{"type": "text", "text": json.dumps(result, indent=2, default=str)}]}

        elif name == "quant_options_scan":
            regime = arguments.get("regime", "BULLISH")
            metrics = {
                "current_price": 565.40,
                "adx": 31.2,
                "rsi": 62.4,
                "price_above_ema": True,
                "ema_bullish": True,
                "macd_bullish": True
            }
            regime_result = {"regime": regime, "metrics": metrics}
            proposal = quant_agent.run(regime_result)
            return {"content": [{"type": "text", "text": json.dumps(proposal, indent=2, default=str)}]}

        elif name == "risk_engine_validate":
            proposal = arguments.get("proposal", {})
            portfolio_state = orchestrator._get_portfolio_state()
            res = risk_engine.risk_engine.check(proposal, portfolio_state)
            return {"content": [{"type": "text", "text": json.dumps(res, indent=2, default=str)}]}

        elif name == "cio_explain_trade":
            proposal = arguments.get("proposal", {})
            regime_res = arguments.get("regime_result", {"regime": "BULLISH", "metrics": {"adx": 30, "rsi": 60}})
            risk_res = arguments.get("risk_check", {"status": "PASS"})
            thesis = cio_agent.run(regime_res, proposal, risk_res)
            return {"content": [{"type": "text", "text": json.dumps(thesis, indent=2, default=str)}]}

        elif name == "execute_alpaca_trade":
            proposal = arguments.get("proposal", {})
            consent_str = arguments.get("consent", "APPROVE")
            consent = {"decision": consent_str, "timestamp": datetime.now(timezone.utc).isoformat()}
            trade_num = arguments.get("trade_number", 1)
            exec_res = execution.run(proposal, consent, trade_num)
            return {"content": [{"type": "text", "text": json.dumps(exec_res, indent=2, default=str)}]}

        elif name == "monitor_positions":
            summary = monitor.get_portfolio_summary()
            details = monitor.get_position_details()
            exits = monitor.check_positions()
            return {"content": [{"type": "text", "text": json.dumps({"summary": summary, "positions": details, "exits_triggered": exits}, indent=2, default=str)}]}

        elif name == "audit_verify_chain":
            verification = audit.verify_chain()
            return {"content": [{"type": "text", "text": json.dumps(verification, indent=2, default=str)}]}

        else:
            return {"isError": True, "content": [{"type": "text", "text": f"Unknown tool: {name}"}]}

    except Exception as exc:
        return {"isError": True, "content": [{"type": "text", "text": f"Error executing tool {name}: {exc}"}]}


def run_stdio_server():
    """Run JSON-RPC 2.0 MCP server loop over stdin/stdout."""
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
            req_id = req.get("id")
            method = req.get("method")
            params = req.get("params", {})

            if method == "initialize":
                response = {
                    "jsonrpc": "2.0",
                    "id": req_id,
                    "result": {
                        "protocolVersion": "2024-11-05",
                        "capabilities": {"tools": {}},
                        "serverInfo": SERVER_INFO,
                    }
                }
            elif method == "notifications/initialized":
                continue
            elif method == "ping":
                response = {"jsonrpc": "2.0", "id": req_id, "result": {}}
            elif method == "tools/list":
                response = {
                    "jsonrpc": "2.0",
                    "id": req_id,
                    "result": {"tools": TOOLS}
                }
            elif method == "tools/call":
                tool_name = params.get("name")
                tool_args = params.get("arguments", {})
                res = handle_tool_call(tool_name, tool_args)
                response = {
                    "jsonrpc": "2.0",
                    "id": req_id,
                    "result": res
                }
            else:
                response = {
                    "jsonrpc": "2.0",
                    "id": req_id,
                    "error": {"code": -32601, "message": f"Method '{method}' not found"}
                }

            sys.stdout.write(json.dumps(response) + "\n")
            sys.stdout.flush()

        except Exception as e:
            err_resp = {
                "jsonrpc": "2.0",
                "id": None,
                "error": {"code": -32700, "message": f"Parse error: {e}"}
            }
            sys.stdout.write(json.dumps(err_resp) + "\n")
            sys.stdout.flush()


if __name__ == "__main__":
    run_stdio_server()
